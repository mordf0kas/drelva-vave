"""Rasterise Michroma into 4-bit alpha glyph tables for the Drelva Vave UI.

  gen_font.py OUT.h

Glyphs cover ASCII 32..95 (the UI draws capitals only). Each face is a fixed-height
cell; every glyph row is packed two pixels per byte, high nibble first.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "assets" / "Michroma-Regular.ttf"
FACES = (("S", 9), ("M", 13), ("L", 19))
FIRST, LAST = 32, 95


def face(name, px):
    font = ImageFont.truetype(str(TTF), px)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    data, table = bytearray(), []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        width = max(adv, 1)
        img = Image.new("L", (width, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        box = img.getbbox()
        width = box[2] if box else 0
        table.append((len(data), width, adv))
        for y in range(height):
            for x in range(0, width, 2):
                hi = img.getpixel((x, y)) >> 4
                lo = img.getpixel((x + 1, y)) >> 4 if x + 1 < width else 0
                data.append(hi << 4 | lo)
    out = [f"static const uint8_t DV_FONT_{name}_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const dv_glyph_t DV_FONT_{name}_GLYPHS[{LAST - FIRST + 1}] = {{")
    out.append("    " + ",".join(f"{{{o},{w},{a}}}" for o, w, a in table))
    out.append("};")
    out.append(f"static const dv_font_t DV_FONT_{name} = "
               f"{{DV_FONT_{name}_DATA, DV_FONT_{name}_GLYPHS, {height}}};")
    return "\n".join(out), len(data)


def main():
    out = Path(sys.argv[1])
    out.parent.mkdir(parents=True, exist_ok=True)
    parts = ["/* Generated by tools/gen_font.py from Michroma (SIL OFL 1.1). Do not edit. */"]
    total = 0
    for name, px in FACES:
        text, size = face(name, px)
        parts.append(text)
        total += size
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"font: {total} bytes of glyph data")


if __name__ == "__main__":
    main()
